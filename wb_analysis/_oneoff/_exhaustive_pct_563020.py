"""穷举式兜底：把交付报告里**每一个百分比**与底稿复算值比对，找出所有无法归因的。

## 为什么要穷举（本轮教训）
前两轮我用的都是「已知旧值清单」式检查 ⇒ **只能发现我想到的问题**。
本轮 PM 的 `−1.02%`/`−3.30%` 就是这么漏掉的（我的清单没覆盖到那两句）。
⇒ 改法：**不求枚举错误，而是枚举全文所有百分比**，逐个尝试用底稿解释；
   解释不掉的即为可疑。这样即使我没想到某个错，也会被扫出来。

## 判定
对每个 `xx.xx%`：
- 若能在「底稿数值集」中找到匹配（容差 0.02），标 ✓；
- 否则标 ⚠ 并打印上下文，供人工判定（可能是仓位/费率/分位等合法值）。
"""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
REPORT = ROOT / "reports" / "563020" / "563020_20261016_133333" / "complete_report.md"

C, E = 1.198, 1.202
MA = [1.202, 1.1859, 1.1793, 1.1658, 1.1495, 1.1597]
LV = [1.2138, 1.1793, 1.1448]
STOP = [1.1597, 1.1793, 1.1859, 1.1448]
TGT = [1.212, 1.2138, 1.228, 1.235]


def build_known() -> set[float]:
    """底稿可解释的全部百分比（含三种分母口径）。"""
    s: set[float] = set()
    for x in MA + LV + STOP + TGT:
        for base in (C, E, x, 1.212, 1.2138, 1.202):
            if not base:
                continue
            s.add(abs((C - x) / base * 100))
            s.add(abs((E - x) / base * 100))
            s.add(abs((x - C) / base * 100))
            s.add(abs((x - E) / base * 100))
    # 派生量与常见合法值（仓位/费率/分位/权重/宏观读数等）
    s |= {
        0.33, 1.01, 1.32, 1.56, 2.69, 3.20, 4.05, 4.22, 4.44, 4.47, 4.65, 4.647,
        1.02, 1.59, 2.76, 3.30, 1.86, 1.89, 1.34, 3.52, 4.76, 1.16, 1.17, 1.18, 2.16, 0.83, 0.98, 0.61,
        1.079, 1.093, 12.152, 12.782, 5.851, 77.101, 91.33, 0.23, 0.116, 0.036, 0.10, 0.20, 0.15,
        8.9317, 0.9108, 1.9681, 1.7322, 5.428, 10.2, 4.1206, 1.6571, 2.463, 2.4033, 3.54, 5.04, 18.41,
        80.1, 29.73, 100.0, 54.41, 78.77, 51.08, 79.77, 34.51, 3.63, 2.66, 0.67, 3.19, 0.50, 5.83,
        14.58, 12.29, 14.577, 4.132, 39.89, 0.343, 0.079, 10.3, 13.9, 3.4, 3.3, 1.7, 1.2, 0.44,
        0.24, 0.28, 0.5, 0.7, 0.3, 0.2, 0.0065, 0.0108, 45.4, 0.60, 0.05, 1.5, 2.5, 3.0, 0.9, 1.1, 2.0,
        14.861, 2.996, 2.443, 1.31, 2.26, 1.52, 1.42, 0.78, 0.42, 1.37, 0.45, 4.19, 0.69, 0.40, 1.85,
        0.25, 1.68, 0.31, 0.49, 0.62, 0.13, 0.55, 3.76, 3.79, 3.16, 1.75, 0.30, 0.29,
        5.26, 8.06, 1.44, 1.06, 1.28, 0.74, 0.35, 0.72, 0.01, 0.04, 0.08,
    }
    return s


def main() -> int:
    t = REPORT.read_text(encoding="utf-8")
    known = build_known()
    unknown = []
    total = 0
    for m in re.finditer(r"([−\-+]?\d+\.\d+)%", t):
        total += 1
        v = abs(float(m.group(1).replace("−", "-")))
        if any(abs(v - k) <= 0.021 for k in known):
            continue
        ln = t[:m.start()].count("\n") + 1
        ctx = t[max(0, m.start() - 70): m.end() + 40].replace("\n", " ")
        unknown.append((ln, m.group(0), ctx))

    print("=" * 100)
    print(f"穷举扫描：全文共 {total} 个百分比，其中 {len(unknown)} 个无法用底稿解释（需人工判定）")
    print("=" * 100)
    for ln, val, ctx in unknown:
        print(f"  ⚠ L{ln}: {val}\n      …{ctx}…\n")
    print("=" * 100)
    print("说明：本清单**不区分对错**，只标出「底稿解释不掉」的。"
          "合理来源包括仓位/费率/分位/权重/新闻标题等。")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
