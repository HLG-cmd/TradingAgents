def main() -> int:
    total, miss = 0, []
    for rel, old, new in EDITS:
        if old == new:
            continue
        p = D / rel
        t = p.read_text(encoding="utf-8")
        if old not in t:
            miss.append((rel, old.replace("\n", " ⏎ ")[:80]))
            continue
        t = t.replace(old, new, 1)
        p.write_text(t, encoding="utf-8", newline="\n")
        total += 1
    print(f"✓ 距入场口径标注：{total} 处")
    if miss:
        print(f"⚠️ 未命中 {len(miss)} 处：")
        for rel, s in miss:
            print(f"   {rel}: {s}")
    return 0


